"""Real PostgreSQL tests; run only against an explicit disposable loopback DB."""

import os
from dataclasses import asdict
from uuid import uuid4

import pytest

psycopg = pytest.importorskip("psycopg")
from psycopg import sql
from psycopg.conninfo import conninfo_to_dict

from adapters.database.promotion_copy import PostgresPromotionCopy
from domain.database import DatabaseBinding


@pytest.fixture
def databases():
    dsn = os.environ.get("SKY_TEST_PROMOTION_POSTGRES_DSN")
    if not dsn:
        pytest.skip("Disposable PostgreSQL required")
    params = conninfo_to_dict(dsn)
    assert params.get("host") == "127.0.0.1" and params.get("dbname") == "postgres"
    names = ["copy_src_" + uuid4().hex[:12], "copy_dst_" + uuid4().hex[:12]]
    with psycopg.connect(**params, autocommit=True) as admin:
        for name in names:
            admin.execute(sql.SQL("CREATE DATABASE {}").format(sql.Identifier(name)))
    factories = [lambda name=name: psycopg.connect(**{**params, "dbname": name}) for name in names]
    bindings = [
        asdict(DatabaseBinding("org", "app", role, "111111111111", "ap-northeast-2", instance, name, "owner"))
        for role, instance, name in zip(
            ["shared_workload", "dedicated_workload"], ["pool", "dedicated"], names
        )
    ]
    yield factories, {"plan_id": "DBP-test", "source": bindings[0], "target": bindings[1]}
    with psycopg.connect(**params, autocommit=True) as admin:
        for name in names:
            admin.execute(sql.SQL("DROP DATABASE {} WITH (FORCE)").format(sql.Identifier(name)))


def seed(connect):
    with connect() as db:
        db.execute(
            "CREATE TABLE scores(id integer PRIMARY KEY, score bigint NOT NULL, label text, payload jsonb)"
        )
        db.execute("INSERT INTO scores VALUES (1,42,'한글', '{\"a\":1}'),(2,0,NULL,NULL)")


def test_copy_preserves_schema_null_unicode_and_rows(databases):
    (source, target), plan = databases
    seed(source)
    receipt = PostgresPromotionCopy(source, target).copy(plan, guard=lambda: None)
    assert receipt["tables"][0]["rows"] == 2
    assert receipt["source_retained"] and not receipt["ready_to_cutover"] and not receipt["routing_changed"]
    with source() as src, target() as dst:
        assert (
            src.execute("SELECT * FROM scores ORDER BY id").fetchall()
            == dst.execute("SELECT * FROM scores ORDER BY id").fetchall()
        )
        with pytest.raises(psycopg.errors.UniqueViolation):
            dst.execute("INSERT INTO scores VALUES (1,1,NULL,NULL)")


def test_identity_copy_preserves_unused_allocated_ids_and_next_insert(databases):
    (source, target), plan = databases
    with source() as db:
        db.execute(
            "CREATE TABLE scores(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,score integer)"
        )
        db.execute("INSERT INTO scores(score) VALUES(42),(84),(126)")
        db.execute("DELETE FROM scores WHERE id=3")
    receipt = PostgresPromotionCopy(source, target).copy(plan, guard=lambda: None)
    assert receipt["sequences"] == [{"table": "scores", "column": "id", "next_value": 4}]
    with target() as db:
        assert db.execute("INSERT INTO scores(score) VALUES(168) RETURNING id").fetchone() == (4,)


@pytest.mark.parametrize(
    "settings", ["ALWAYS", "BY DEFAULT (CACHE 2)", "BY DEFAULT (CYCLE)", "BY DEFAULT (START WITH 10)"]
)
def test_nonstandard_identity_is_rejected_before_target_mutation(databases, settings):
    (source, target), plan = databases
    with source() as db:
        db.execute(
            sql.SQL("CREATE TABLE scores(id bigint GENERATED {} AS IDENTITY PRIMARY KEY)").format(
                sql.SQL(settings)
            )
        ) if settings == "ALWAYS" else db.execute(
            sql.SQL("CREATE TABLE scores(id bigint GENERATED BY DEFAULT AS IDENTITY {})").format(
                sql.SQL(settings.removeprefix("BY DEFAULT "))
            )
        )
    with pytest.raises(ValueError, match="Unsupported"):
        PostgresPromotionCopy(source, target).copy(plan, guard=lambda: None)
    with target() as db:
        assert db.execute("SELECT to_regclass('scores')").fetchone() == (None,)


def test_final_identity_refresh_and_reverse_recovery_preserve_next_value(databases):
    from adapters.database.promotion_sync import PostgresPromotionSynchronizer

    (source, target), plan = databases
    with source() as db:
        db.execute(
            "CREATE TABLE scores(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,score integer)"
        )
        db.execute("INSERT INTO scores(score) VALUES(42)")
    baseline = PostgresPromotionCopy(source, target).copy(plan, guard=lambda: None)
    with source() as db:
        db.execute("INSERT INTO scores(score) VALUES(84)")
    sync = PostgresPromotionSynchronizer(source, target)
    final = sync.refresh(plan, expected_destination=baseline, guard=lambda: None)
    with target() as db:
        assert db.execute("INSERT INTO scores(score) VALUES(126) RETURNING id").fetchone() == (3,)
    recovered = sync.refresh(plan, expected_destination=final, guard=lambda: None, reverse=True)
    assert recovered["sequences"] == [{"table": "scores", "column": "id", "next_value": 4}]
    with source() as db:
        assert db.execute("INSERT INTO scores(score) VALUES(168) RETURNING id").fetchone() == (4,)


