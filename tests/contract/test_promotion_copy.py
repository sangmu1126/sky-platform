def test_identity_restart_rolls_back_with_failed_refresh(databases):
    from unittest.mock import patch

    from adapters.database.promotion_copy import _restart_sequences, _sequence_positions
    from adapters.database.promotion_sync import PostgresPromotionSynchronizer

    (source, target), plan = databases
    with source() as db:
        db.execute("CREATE TABLE scores(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)")
        db.execute("INSERT INTO scores DEFAULT VALUES")
    baseline = PostgresPromotionCopy(source, target).copy(plan, guard=lambda: None)
    with source() as db:
        db.execute("INSERT INTO scores DEFAULT VALUES")

    def fail_after_restart(connection, positions, *, guard):
        _restart_sequences(connection, positions, guard=guard)
        raise RuntimeError("Final checkpoint failed")

    with (
        patch("adapters.database.promotion_sync._restart_sequences", side_effect=fail_after_restart),
        pytest.raises(RuntimeError),
    ):
        PostgresPromotionSynchronizer(source, target).refresh(
            plan, expected_destination=baseline, guard=lambda: None
        )
    with target() as db:
        assert _sequence_positions(db) == baseline["sequences"]
        assert db.execute("SELECT id FROM scores").fetchall() == [(1,)]


