def test_fresh_review_revalidates_destination_without_overwriting_new_source_writes(databases):
    (source, target), plan = databases
    plan = {**plan, "source_revision": "a" * 64}
    seed(source)
    copier = PostgresPromotionCopy(source, target)
    baseline = copier.copy(plan, guard=lambda: None)
    with source() as db:
        db.execute("INSERT INTO scores VALUES(3,99,NULL,NULL)")
    fresh = {**plan, "plan_id": "DBP-" + "b" * 16}
    observed = copier.revalidate_destination(fresh, plan, baseline, guard=lambda: None)
    assert observed["plan_id"] == fresh["plan_id"]
    assert observed["source_snapshot_plan_id"] == plan["plan_id"]
    assert observed["requires_final_write_freeze"]
    assert observed["verified_scope"] == "revalidated_destination_snapshot"
    with target() as db:
        assert db.execute("SELECT count(*) FROM scores").fetchone() == (2,)


@pytest.mark.parametrize("fault", ["source_revision", "target_rows", "target_sequence", "schema"])
def test_revalidation_never_adopts_changed_copy_or_different_source(databases, fault):
    (source, target), plan = databases
    plan = {**plan, "source_revision": "a" * 64}
    with source() as db:
        db.execute(
            "CREATE TABLE scores(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,score integer)"
        )
        db.execute("INSERT INTO scores(score) VALUES(42)")
    copier = PostgresPromotionCopy(source, target)
    baseline = copier.copy(plan, guard=lambda: None)
    fresh = {**plan, "plan_id": "DBP-" + "b" * 16}
    if fault == "source_revision":
        fresh["source_revision"] = "c" * 64
    else:
        with target() as db:
            if fault == "target_rows":
                db.execute("UPDATE scores SET score=99")
            elif fault == "target_sequence":
                db.execute("SELECT nextval(pg_get_serial_sequence('scores','id'))")
            else:
                db.execute("ALTER TABLE scores ADD COLUMN changed text")
    with pytest.raises(ValueError):
        copier.revalidate_destination(fresh, plan, baseline, guard=lambda: None)
