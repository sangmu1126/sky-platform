"""Internal trusted recovery execution, never arbitrary worker/HTTP receipts."""

from collections.abc import Callable
from typing import Protocol


class IncidentRecoveryRuntime(Protocol):
    def preflight(self, job: dict, recovery_id: str, *, guard: Callable) -> dict: ...
    def activate(self, plan: dict, *, guard: Callable) -> dict: ...
    def deploy(self, plan: dict, *, guard: Callable) -> dict: ...
    def verify(self, plan: dict, submitted: dict, *, guard: Callable) -> dict: ...
    def restrict(self, plan: dict) -> dict: ...
